# --- Reading / Listening generation ------------------------------------------
_COMPREHENSION_SCHEMA = {
    "type": "object",
    "properties": {
        "title": {"type": "string"},
        "body": {"type": "string"},
        "questions": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "prompt": {"type": "string"},
                    "options": {"type": "array", "items": {"type": "string"}},
                    "answer_index": {"type": "integer"},
                    "explanation": {"type": "string"},
                },
                "required": ["prompt", "options", "answer_index", "explanation"],
                "additionalProperties": False,
            },
        },
    },
    "required": ["title", "body", "questions"],
    "additionalProperties": False,
}

_READING_PROMPT = (
    "Create one IELTS Academic Reading practice item at band {band} difficulty. Write an "
    "informative academic passage of 550-750 words with a title, split into 4-6 paragraphs "
    "(separate them with blank lines), on an interesting non-fiction topic (science, history, "
    "environment, society, technology). Then write {n} questions in authentic IELTS style: "
    "the first half TRUE/FALSE/NOT GIVEN statements (options exactly "
    "['TRUE', 'FALSE', 'NOT GIVEN'] — statement in the prompt, answer_index 0-based; include "
    "at least one NOT GIVEN), the rest multiple-choice with exactly 4 plausible options "
    "testing main ideas, detail, inference and vocabulary. For every question give a "
    "one-sentence explanation that quotes or paraphrases the exact part of the passage "
    "which settles it, so a learner can see why the answer is right."
)

_LISTENING_PROMPT = (
    "Create one IELTS Listening practice item at band {band} difficulty. Write a natural spoken "
    "MONOLOGUE or DIALOGUE script of 200-300 words (e.g. a lecture excerpt, a tour guide, or two "
    "people arranging plans) that will be read aloud to the learner. Then write {n} multiple-"
    "choice questions testing comprehension of specific details and gist. Each question has "
    "exactly 4 options with one correct answer (answer_index is 0-based). For every "
    "question give a one-sentence explanation pointing at the line of the script that "
    "settles it, so a learner can see why the answer is right."
)


async def generate_test(
    db: AsyncSession, user: User, client: AiClient, kind: str, band: float, count: int = 6
) -> Tuple[UUID, Dict[str, Any]]:
    """Generate a Reading/Listening test, persist it with its answer key, and
    return (test_id, client_payload) where client_payload omits the answers."""
    if kind == "reading":
        template, count = _READING_PROMPT, 8  # full-length passage, TFNG + MCQ
    else:
        template = _LISTENING_PROMPT
    system = (
        "You are an experienced IELTS test writer. Produce authentic, original IELTS-style "
        "material. Never reproduce copyrighted texts."
    )
    prompt = template.format(band=band, n=count)
    # Generous limit: a 750-word passage + 8 questions as JSON runs to several
    # thousand tokens, and a truncated response fails JSON parsing (seen live).
    data = await client.json(
        system=system, prompt=prompt, schema=_COMPREHENSION_SCHEMA, max_tokens=8192
    )

    questions = [
        q for q in data.get("questions", [])
        if isinstance(q.get("options"), list) and len(q["options"]) >= 2
    ]
    if not questions:
        raise ValueError("AI produced no questions")

    payload = {"title": str(data.get("title", "")), "body": str(data.get("body", "")), "questions": questions}
    test = IeltsTest(user_id=user.id, kind=kind, payload_json=json.dumps(payload))
    db.add(test)
    await db.flush()

    # Client view: same, but each question strips answer_index and explanation —
    # both are revealed only after grading.
    client_payload = {
        "title": payload["title"],
        "body": payload["body"],
        "questions": [
            {"prompt": q["prompt"], "options": q["options"]} for q in questions
        ],
    }
    return test.id, client_payload


async def start_bank_test(
    db: AsyncSession, user: User, kind: str, item_id: str
) -> Tuple[UUID, Dict[str, Any]]:
    """Start a built-in bank passage: persist it as a normal IeltsTest (with its
    answer key and bank id) so grading/XP/history reuse the same pipeline. No AI
    call, no quota."""
    from app.services.ielts_bank import bank_item

    item = bank_item(kind, item_id)
    if item is None:
        raise LookupError("bank item not found")
    payload = {
        "title": item["title"],
        "body": item["body"],
        "questions": item["questions"],
        "bank_id": item["id"],
    }
    test = IeltsTest(user_id=user.id, kind=kind, payload_json=json.dumps(payload))
    db.add(test)
    await db.flush()
    client_payload = {
        "title": payload["title"],
        "body": payload["body"],
        "questions": [
            {"prompt": q["prompt"], "options": q["options"]} for q in item["questions"]
        ],
    }
    return test.id, client_payload


async def completed_bank_ids(db: AsyncSession, user: User, kind: str) -> List[str]:
    """Bank items this user has already completed (marked ✓ in the list)."""
    skill = "reading" if kind == "reading" else "listening"
    rows = await db.scalars(
        select(IeltsResult.detail).where(
            IeltsResult.user_id == user.id, IeltsResult.skill == skill
        )
    )
    done: List[str] = []
    for detail in rows:
        if not detail:
            continue
        try:
            bank_id = json.loads(detail).get("bank_id")
        except ValueError:
            continue
        if bank_id:
            done.append(bank_id)
    return done


@dataclass
class GradeResult:
    correct: int
    total: int
    band: float
    # True when the test is too short for a single band to mean much; the client
    # shows a range and a caveat rather than a precise figure.
    approximate: bool
    # Why each answer is right, revealed with the answers after grading. The
    # results screen used to show only which option was correct.
    explanations: List[str]
    answers: List[int]  # correct answer_index per question, revealed after submit
    reward: RewardSummary


async def grade_test(
    db: AsyncSession, user: User, test_id: UUID, submitted: List[int],
    mock_session_id: Optional[UUID] = None,
) -> GradeResult:
    """Grade a submitted Reading/Listening test against the stored answer key."""
    test = await db.scalar(
        select(IeltsTest).where(IeltsTest.id == test_id, IeltsTest.user_id == user.id)
    )
    if test is None:
        raise LookupError("test not found")
    payload = json.loads(test.payload_json)
    questions = payload["questions"]
    answers = [int(q["answer_index"]) for q in questions]
    explanations = [str(q.get("explanation", "")).strip() for q in questions]

    correct = sum(
        1 for i, ans in enumerate(answers) if i < len(submitted) and submitted[i] == ans
    )
    total = len(answers)
    skill = "reading" if test.kind == "reading" else "listening"
    band = band_from_ratio(correct / total, skill) if total else 0.0
    approximate = total < RELIABLE_QUESTION_COUNT
    xp = XP_READING if test.kind == "reading" else XP_LISTENING
    reward = await apply_skill_xp(db, user, xp)
    detail: Dict[str, Any] = {"correct": correct, "total": total}
    if payload.get("bank_id"):
        detail["bank_id"] = payload["bank_id"]  # marks the bank item as done
    db.add(
        IeltsResult(
            user_id=user.id, skill=skill, band=band, detail=json.dumps(detail),
            mock_session_id=mock_session_id,
        )
    )
    # One-shot content: drop the stored test after grading.
    await db.delete(test)
    return GradeResult(
        correct=correct,
        total=total,
        band=band,
        approximate=approximate,
        answers=answers,
        explanations=explanations,
        reward=reward,
    )


