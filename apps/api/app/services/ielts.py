"""IELTS practice engine — AI-generated content + band scoring.

All content is generated by the AI chain (copyright-safe, unlimited), in real
IELTS formats:
- Reading: an academic passage + comprehension questions.
- Listening: a spoken-style script (read aloud by the browser) + questions.
- Writing: Task 1 / Task 2 prompts, scored against the four IELTS criteria.
- Speaking: handled by the existing Coach (examiner, Parts 1-3, band report).

Reading/Listening tests are graded server-side; the client never sees the
answer key.
"""
